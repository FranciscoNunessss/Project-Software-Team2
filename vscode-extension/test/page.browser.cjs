const path = require('node:path')

const vm = require('node:vm')
const assert = require('node:assert/strict')
const repo = path.resolve(__dirname, '../..')
require(path.join(repo, 'vscode-extension/test/helpers')).installVscode({})
const {Dashboard} = require(path.join(repo, 'vscode-extension/dist/dashboard'))
const {chromium} = require(path.join(repo, 'e2e/node_modules/@playwright/test'))
const dash = new Dashboard({auth:'none',onDidChangeSession:()=>{}},{onDidAnalyse:()=>{},results:new Map()},{},{})
const view = {webview:{cspSource:'https://synthetic.invalid',onDidReceiveMessage:()=>{}},onDidChangeVisibility:()=>{},onDidDispose:()=>{}}
dash.resolveWebviewView(view)
const html = view.webview.html
new vm.Script(html.match(/<script[^>]*>([\s\S]*?)<\/script>/)[1])
const data={type:'data',tab:'analyse',options:[],chats:[],messages:[],chatModel:'',auto:null,assessment:null,streaming:false,analysing:false}
;(async()=>{
 const browser=await chromium.launch({headless:true})
 try{
  const page=await browser.newPage({viewport:{width:340,height:800}})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.evaluate(()=>{window.__sent=[];window.acquireVsCodeApi=()=>({postMessage:m=>window.__sent.push(m),getState:()=>({}),setState:()=>{}})})
  await page.setContent(html)
  async function post(message){await page.evaluate(m=>window.postMessage(m,'*'),message);await page.waitForTimeout(30)}
  await post(data)
  await page.locator('#task').fill('Synthetic request')
  assert.equal(await page.getByRole('button',{name:'Analyse',exact:true}).isEnabled(),true)
  assert.equal(await page.locator('#sendbtn').isEnabled(),true)
  await page.getByRole('button',{name:'Analyse',exact:true}).click()
  assert.ok((await page.evaluate(()=>window.__sent)).some(m=>m.type==='analyse'))
  await post({type:'assistantState',data:{analysing:true}})
  assert.equal(await page.getByRole('button',{name:'Analysing…',exact:true}).isDisabled(),true)
  assert.equal(await page.locator('#task').inputValue(),'Synthetic request')
  await post({type:'assistantState',data:{analysing:false}})
  await post({type:'chatStart',user:'Synthetic request'})
  await post({type:'delta',text:'First fragment'})
  await post({type:'assistantState',data:{streaming:true}})
  await post({...data,streaming:true})
  await post({type:'delta',text:' and second fragment'})
  assert.match(await page.locator('#msgs').innerText(),/First fragment and second fragment/)
  await post({type:'assistantState',data:{streaming:false}})
  assert.match(await page.locator('#msgs').innerText(),/First fragment and second fragment/)
  await post({type:'assistantState',data:{streaming:false,messages:[{role:'assistant',who:'AdaptAI',text:'Final saved reply',error:''}],chats:[]}})
  assert.match(await page.locator('#msgs').innerText(),/Final saved reply/)
  assert.doesNotMatch(await page.locator('#msgs').innerText(),/First fragment/)

  await page.setViewportSize({width:850,height:800})
  if (await page.getByRole('button',{name:'Close analysis',exact:true}).count()) await page.getByRole('button',{name:'Close analysis',exact:true}).click()
  await page.locator('#nav button[data-tab="models"]').click()
  assert.match(await page.locator('#main').innerText(),/Loading…/)
  assert.equal(await page.locator('#task').count(),0,'the previous tab is no longer interactive')
  await post(data)
  assert.match(await page.locator('#main').innerText(),/Loading…/,'an old tab response cannot take over navigation')
  const models={type:'data',tab:'models',project:[],configs:[],evaluations:[],relay:{state:'off',text:''}}
  await post(models)
  assert.match(await page.locator('#main').innerText(),/Ready by default/)
  await post({...models,refreshing:true})
  assert.match(await page.locator('#main').innerText(),/Updating…/)
  assert.match(await page.locator('#main').innerText(),/Ready by default/)
  await post({...models,refreshError:'Synthetic network failure'})
  assert.match(await page.locator('#main').innerText(),/Could not update/)
  assert.match(await page.locator('#main').innerText(),/Ready by default/)
  await page.locator('#nav button[data-tab="analyse"]').click()
  await post(data)
  assert.equal(await page.locator('#task').inputValue(),'Synthetic request')
  const previousMain=await page.locator('#main').innerText()
  await post({type:'connection',online:false,email:null})
  assert.equal(await page.locator('#main').innerText(),previousMain,'connection checks update only the header')
  assert.match(await page.locator('#acct').innerText(),/Offline/)
  await page.locator('#nav button[data-tab="progress"]').click()
  const progress=require('./fixtures/progress-with-coaching.json')
  await post(progress)
  assert.deepEqual(errors,[],'a saved Educator report must not crash My Progress')
  const progressText=await page.locator('#main').innerText()
  for (const expected of ['Your judgement over time.', 'Synthetic saved Educator summary.', 'Synthetic saved suggestion', 'Synthetic over-provisioning explanation.', 'Session history', 'Synthetic API comparison']) assert.ok(progressText.includes(expected),expected+' must be visible')
  await page.getByRole('button',{name:'Recommendation match',exact:true}).click()
  assert.ok(await page.getByRole('img',{name:'Recommendation match by saved session'}).count())
  await post({...progress,coaching:null})
  assert.match(await page.locator('#main').innerText(),/Your judgement over time\./)
  assert.match(await page.locator('#main').innerText(),/Suggestions not available\./)
  await post({...progress,outcomes:{...progress.outcomes,by_model:null}})
  assert.match(await page.getByRole('alert').innerText(),/Could not display this page/)
  assert.doesNotMatch(await page.locator('#main').innerText(),/TypeError|\.length|null/)
  await page.getByRole('button',{name:'Try again',exact:true}).click()
  assert.equal((await page.evaluate(()=>window.__sent)).at(-1).type,'ready')
  await post(progress)
  assert.match(await page.locator('#main').innerText(),/Synthetic saved Educator summary\./)
  await page.locator('#nav button[data-tab="analyse"]').click()
  await post(data)
  await post({type:'resetTabs',signedOut:true})
  assert.match(await page.locator('#main').innerText(),/Sign in to use AdaptAI/)
  await post({type:'data',tab:'analyse',signedOut:true})
  assert.match(await page.locator('#main').innerText(),/Sign in to use AdaptAI/)
  await post({type:'assistantState',data:{messages:[{text:'Stale reply'}]}})
  assert.doesNotMatch(await page.locator('#main').innerText(),/Stale reply/)
  assert.deepEqual(errors,[])
  console.log('PASS: webview navigation, drafts, streaming, scope reset; populated My Progress with saved Educator report, patterns, suggestions, charts and history; missing coaching; malformed-data error and Retry recovery; no page errors.')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
